export function presetFor(settings) {
  const preset = voicePresets[settings.effect] || voicePresets.clean;
  return {
    ...preset,
    pitch: settings.voicePitch ?? preset.pitch,
    drive: settings.voiceDrive ?? preset.drive,
    body: settings.voiceBody ?? preset.body,
    ring: settings.voiceRing != null ? settings.voiceRing / 100 : preset.ring,
  };
}
